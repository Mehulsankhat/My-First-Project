-- School Gallery RLS repair
-- Safe to re-run. Existing gallery rows and uploaded files are preserved.

create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  caption text,
  is_published boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.gallery_items add column if not exists caption text;
alter table public.gallery_items add column if not exists is_published boolean not null default true;
alter table public.gallery_items add column if not exists created_by uuid references auth.users(id);
alter table public.gallery_items enable row level security;

-- Remove old policies on this table so an older restrictive policy cannot block new uploads.
do $$
declare p record;
begin
  for p in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'gallery_items'
  loop
    execute format('drop policy if exists %I on public.gallery_items', p.policyname);
  end loop;
end $$;

create policy gallery_public_read
on public.gallery_items for select
to anon, authenticated
using (is_published = true);

create policy gallery_owner_read_all
on public.gallery_items for select
to authenticated
using (created_by = (select auth.uid()));

create policy gallery_owner_insert
on public.gallery_items for insert
to authenticated
with check (created_by = (select auth.uid()));

create policy gallery_owner_update
on public.gallery_items for update
to authenticated
using (created_by = (select auth.uid()))
with check (created_by = (select auth.uid()));

create policy gallery_owner_delete
on public.gallery_items for delete
to authenticated
using (created_by = (select auth.uid()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('school-gallery', 'school-gallery', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update
set public = true,
    file_size_limit = 5242880,
    allowed_mime_types = array['image/jpeg','image/png','image/webp'];

-- Bucket-specific policies: each signed-in user can manage files inside their own UID folder.
drop policy if exists school_gallery_public_read on storage.objects;
drop policy if exists school_gallery_owner_insert on storage.objects;
drop policy if exists school_gallery_owner_update on storage.objects;
drop policy if exists school_gallery_owner_delete on storage.objects;

create policy school_gallery_public_read
on storage.objects for select
to anon, authenticated
using (bucket_id = 'school-gallery');

create policy school_gallery_owner_insert
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'school-gallery'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

create policy school_gallery_owner_update
on storage.objects for update
to authenticated
using (
  bucket_id = 'school-gallery'
  and (storage.foldername(name))[1] = (select auth.uid())::text
)
with check (
  bucket_id = 'school-gallery'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

create policy school_gallery_owner_delete
on storage.objects for delete
to authenticated
using (
  bucket_id = 'school-gallery'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);
