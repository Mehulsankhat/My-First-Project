-- Examination & marks management. Run once in Supabase SQL Editor.
create table if not exists public.exam_marks (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  academic_year text not null,
  exam_name text not null,
  subject text not null,
  marks_obtained numeric(8,2) not null check (marks_obtained >= 0),
  max_marks numeric(8,2) not null check (max_marks > 0),
  remarks text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint exam_marks_student_exam_subject_unique
    unique (student_id, academic_year, exam_name, subject),
  constraint exam_marks_obtained_within_max
    check (marks_obtained <= max_marks)
);

create index if not exists exam_marks_student_idx on public.exam_marks(student_id);
create index if not exists exam_marks_year_exam_idx on public.exam_marks(academic_year, exam_name);

alter table public.exam_marks enable row level security;

drop policy if exists "Staff can read exam marks" on public.exam_marks;
create policy "Staff can read exam marks" on public.exam_marks
for select to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role in ('admin','principal','teacher')
));

drop policy if exists "Staff can add exam marks" on public.exam_marks;
create policy "Staff can add exam marks" on public.exam_marks
for insert to authenticated
with check (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role in ('admin','principal','teacher')
));

drop policy if exists "Staff can edit exam marks" on public.exam_marks;
create policy "Staff can edit exam marks" on public.exam_marks
for update to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role in ('admin','principal','teacher')
))
with check (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role in ('admin','principal','teacher')
));

drop policy if exists "Staff can delete exam marks" on public.exam_marks;
create policy "Staff can delete exam marks" on public.exam_marks
for delete to authenticated
using (exists (
  select 1 from public.profiles p
  where p.id = auth.uid() and p.role in ('admin','principal','teacher')
));

grant select, insert, update, delete on public.exam_marks to authenticated;
grant usage, select on sequence public.exam_marks_id_seq to authenticated;
