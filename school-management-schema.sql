-- Government Secondary School, Bildi: extended school-management schema
-- Run this in Supabase SQL Editor. Existing profiles/notices/homework tables are preserved.

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  admission_no text unique not null,
  full_name text not null,
  standard text not null,
  stream text not null default 'General',
  division text default 'A',
  roll_no integer,
  date_of_birth date,
  gender text check (gender in ('Male','Female','Other')),
  guardian_name text,
  guardian_phone text,
  address text,
  status text not null default 'active' check (status in ('active','inactive','transferred')),
  created_at timestamptz not null default now()
);

-- Safe upgrade for existing databases that already have the students table.
alter table public.students add column if not exists stream text not null default 'General';
alter table public.students add column if not exists photo_url text;

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  attendance_date date not null default current_date,
  status text not null check (status in ('present','absent','late','leave')),
  remarks text,
  marked_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique(student_id, attendance_date)
);

create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  exam_name text not null,
  standard text not null,
  subject text not null,
  exam_date date,
  total_marks numeric(7,2) not null default 100 check (total_marks > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.exam_results (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  marks_obtained numeric(7,2) not null check (marks_obtained >= 0),
  remarks text,
  created_at timestamptz not null default now(),
  unique(exam_id, student_id)
);

create table if not exists public.timetable (
  id bigint generated by default as identity primary key,
  standard text not null,
  stream text not null default 'General',
  division text default 'A',
  weekday smallint not null check (weekday between 1 and 7),
  period_no smallint not null check (period_no > 0),
  start_time time not null,
  end_time time not null,
  subject text not null,
  teacher_name text,
  created_at timestamptz not null default now(),
  unique(standard, division, weekday, period_no),
  check (end_time > start_time)
);

create table if not exists public.fee_records (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  fee_type text not null,
  amount numeric(10,2) not null check (amount >= 0),
  paid_amount numeric(10,2) not null default 0 check (paid_amount >= 0),
  due_date date,
  payment_date date,
  payment_note text,
  created_at timestamptz not null default now(),
  check (paid_amount <= amount)
);

create table if not exists public.school_events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  event_date date not null,
  location text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  caption text,
  is_published boolean not null default false,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists students_standard_idx on public.students(standard, division);
create index if not exists attendance_date_idx on public.attendance(attendance_date);
create index if not exists exam_results_student_idx on public.exam_results(student_id);
create index if not exists events_date_idx on public.school_events(event_date);

-- Enable RLS on all sensitive tables.
alter table public.students enable row level security;
alter table public.attendance enable row level security;
alter table public.exams enable row level security;
alter table public.exam_results enable row level security;
alter table public.timetable enable row level security;
alter table public.fee_records enable row level security;
alter table public.school_events enable row level security;
alter table public.gallery_items enable row level security;

-- Helper checks the signed-in user's role in profiles. Profiles.id must match auth.users.id.
create or replace function public.current_school_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() limit 1 $$;

-- Admin has full access. Teachers can read and manage learning records, but not fees.
-- Student/parent portal policies should be added only after their account-to-student mapping exists.
do $$ declare t text; begin
  foreach t in array array['students','attendance','exams','exam_results','timetable','fee_records','school_events','gallery_items'] loop
    execute format('drop policy if exists %I on public.%I', t || '_admin_all', t);
    execute format('create policy %I on public.%I for all to authenticated using (public.current_school_role() = ''admin'') with check (public.current_school_role() = ''admin'')', t || '_admin_all', t);
  end loop;
end $$;

-- Teacher permissions: student roster and academic operations only.
drop policy if exists students_teacher_read on public.students;
create policy students_teacher_read on public.students for select to authenticated
using (public.current_school_role() in ('teacher','admin'));

-- Teachers may add new student records. Student deletion remains admin-only.
drop policy if exists students_teacher_insert on public.students;
create policy students_teacher_insert on public.students for insert to authenticated
with check (public.current_school_role() = 'teacher');

drop policy if exists attendance_teacher_all on public.attendance;
create policy attendance_teacher_all on public.attendance for all to authenticated
using (public.current_school_role() = 'teacher') with check (public.current_school_role() = 'teacher');

drop policy if exists exams_teacher_read on public.exams;
create policy exams_teacher_read on public.exams for select to authenticated
using (public.current_school_role() in ('teacher','admin'));

drop policy if exists exam_results_teacher_all on public.exam_results;
create policy exam_results_teacher_all on public.exam_results for all to authenticated
using (public.current_school_role() = 'teacher') with check (public.current_school_role() = 'teacher');

drop policy if exists timetable_staff_read on public.timetable;
create policy timetable_staff_read on public.timetable for select to authenticated
using (public.current_school_role() in ('teacher','admin'));

drop policy if exists events_staff_read on public.school_events;
create policy events_staff_read on public.school_events for select to authenticated
using (public.current_school_role() in ('teacher','admin'));

drop policy if exists gallery_public_read on public.gallery_items;
create policy gallery_public_read on public.gallery_items for select to anon, authenticated
using (is_published = true);

